import { useQuery, useQueryClient } from '@tanstack/react-query'
import { ProactiveExtras } from '../components/proactive/ProactiveExtras'
import type { AppInfo } from '../../../shared/types'
import { api, errorMessage } from '../lib/api'
import { BackupSection } from '../components/backup/BackupSection'
import { ShellSettingsSection } from '../components/shell/ShellSettingsSection'
import { PrivacySection } from '../components/settings/PrivacySection'
import { CloudSettingsSection } from '../components/settings/CloudSettingsSection'
import { OwnerAliasesSection } from '../components/settings/OwnerAliasesSection'
import { ProactiveSection } from '../components/settings/ProactiveSection'
import { LanguageSection } from '../components/settings/LanguageSection'
import { copiedToast } from '../components/Toaster'
import { tr } from '../lib/i18n'

export function Settings() {
  const qc = useQueryClient()
  const info = useQuery<AppInfo>({ queryKey: ['app-info'], queryFn: api.info, staleTime: 10_000 })

  const data = info.data
  const diagnostics = data
    ? [
        `app=${data.appVersion}`,
        `electron=${data.electronVersion}`,
        `platform=${data.platform}`,
        `root=${data.root}`,
        `port=${data.port}`,
        `bin=${data.bin ?? '(missing)'}`,
        `token=${data.tokenPresent ? 'present' : 'missing'}`
      ].join('\n')
    : ''

  async function open(kind: 'root' | 'config' | 'logs' | 'viewer'): Promise<void> {
    try {
      await api.open(kind)
    } catch (error) {
      alert(errorMessage(error))
    }
  }

  return (
    <div className="page">
      <header className="page-head">
        <div>
          <div className="eyebrow">Settings</div>
          <h2>{tr('Settings & diagnostics', '设置与诊断')}</h2>
          <p className="muted">{tr('Only local paths and versions are shown here; the token is never displayed.', '这里只展示本地路径与版本；token 不会显示。')}</p>
        </div>
      </header>

      {info.isError ? <div className="banner bad compact">{errorMessage(info.error)}</div> : null}

      <LanguageSection />

      <section className="grid two">
        <div className="card">
          <div className="card-head">
            <h3>Runtime</h3>
            <span className={`chip ${data?.tokenPresent ? 'ok' : 'warn'}`}>
              {data?.tokenPresent ? tr('Token loaded', 'token 已加载') : tr('Token missing', 'token 缺失')}
            </span>
          </div>
          <dl className="kv">
            <div>
              <dt>{tr('Data root', '数据根')}</dt>
              <dd className="mono small">{data?.root ?? '—'}</dd>
            </div>
            <div>
              <dt>{tr('Port', '端口')}</dt>
              <dd className="mono">{data?.port ?? '—'}</dd>
            </div>
            <div>
              <dt>persome</dt>
              <dd className="mono small">{data?.bin ?? tr('Not found', '未找到')}</dd>
            </div>
            <div>
              <dt>{tr('Config', '配置')}</dt>
              <dd className="mono small">{data?.configPath ?? '—'}</dd>
            </div>
          </dl>
          <div className="card-foot wrap">
            <button className="btn ghost small" onClick={() => void open('root')}>
              {tr('Open data folder', '打开数据目录')}
            </button>
            <button className="btn ghost small" onClick={() => void open('config')}>
              {tr('Show config', '显示配置')}
            </button>
            <button className="btn ghost small" onClick={() => void open('logs')}>
              {tr('Open logs', '打开日志')}
            </button>
            <button className="btn ghost small" onClick={() => void open('viewer')}>
              {tr('Official viewer', '官方查看器')}
            </button>
          </div>
        </div>

        <div className="card">
          <div className="card-head">
            <h3>{tr('About', '关于')}</h3>
          </div>
          <dl className="kv">
            <div>
              <dt>{tr('App', '应用')}</dt>
              <dd>Navalia {data?.appVersion ?? ''}</dd>
            </div>
            <div>
              <dt>Electron</dt>
              <dd>{data?.electronVersion ?? '—'}</dd>
            </div>
            <div>
              <dt>{tr('Platform', '平台')}</dt>
              <dd>{data?.platform ?? '—'}</dd>
            </div>
          </dl>
          <p className="muted small about">
            {tr(
              'Unofficial local viewer. It reads data generated by the open-source Runtime in ~/.persome on this Mac. By default it never signs in or uploads; cloud features are optional, off by default and need you to turn them on. No telemetry. The open-source Runtime code is licensed under Apache-2.0.',
              '非官方本地查看器。读取本机 ~/.persome 中由开源 Runtime 生成的数据；默认不登录、不上传；云端功能可选、默认关闭，需你开启；无遥测。开源 Runtime 代码遵循 Apache-2.0。'
            )}
          </p>
          <div className="card-foot">
            <button className="btn ghost small" onClick={() => void api.copy(diagnostics).then(() => copiedToast(tr('diagnostics', '诊断信息')))}>
              {tr('Copy diagnostics', '复制诊断信息')}
            </button>
            <button
              className="btn ghost small"
              data-testid="settings-reopen-onboarding"
              onClick={async () => {
                await window.lens.onboarding.reset()
                await qc.invalidateQueries({ queryKey: ['onboarding', 'status'] })
              }}
            >
              {tr('Reopen onboarding', '重新打开引导')}
            </button>
          </div>
        </div>
      </section>

      <OwnerAliasesSection />

      <ShellSettingsSection />

      <ProactiveSection />
      <ProactiveExtras />

      <PrivacySection />

      <CloudSettingsSection />

      <BackupSection />
    </div>
  )
}
